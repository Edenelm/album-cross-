-- Topic 6 (Eden 2026-10-24): normal-week check. Is the >$20 payers' drop after close just "return to normal"
-- (players picked for spending a lot in a period tend to spend less in any later period)?
-- Same players and albums as topic6_calendar_neutral_return_2026-10-24.sql (standard population, status on close-1, 3 albums per game).
-- Spend level and usual pace are re-based on album days 0-20 (pace_a = $ a day). Compared windows, both vs pace_a:
--   mid7 = album days 21-27, a normal mid-album week with no close; after7 = close+1..+7 (week after close).
-- If >$20 players also fall to ~90% in the normal week, the drop after close is mostly return to normal, not the album end.
-- Results: claude/topic6-normal-week-check-2026-10-24.md

-- ===== DISNEY 12/14/15 (solitaire-dreams-411507) =====
WITH ud AS (
  SELECT album_id, user_id, date_dim, album_open_date AS a_start, album_close_date AS a_end,
    IFNULL(unique_common_stickers_lt,0) + IFNULL(unique_golden_stickers_lt,0) + IFNULL(unique_royal_stickers_tl,0) AS uniq,
    IFNULL(login_ratio,-1) AS lr, IFNULL(user_album_count,1) AS uac, IFNULL(special_user_flag,FALSE) AS excl, IFNULL(album_spent_today,0) AS spend
  FROM `solitaire-dreams-411507.bi_prod.user_daily_album`
  WHERE date_dim BETWEEN DATE '2026-05-11' AND DATE '2026-10-05' AND album_id IN (12,14,15) AND date_dim <= album_close_date),
bad AS (SELECT DISTINCT user_id FROM `solitaire-dreams-411507.bi_prod.solitaire_user_daily_metrics_agg_df`
  WHERE date_dim BETWEEN DATE '2026-05-11' AND DATE '2026-10-12' AND exclude_reason IS NOT NULL),
u AS (
  SELECT a.album_id, a.user_id,
    SUM(IF(a.date_dim < a.a_end, a.spend, 0)) AS alb_rev,
    SUM(IF(a.date_dim BETWEEN DATE_SUB(a.a_end, INTERVAL 7 DAY) AND DATE_SUB(a.a_end, INTERVAL 1 DAY), a.spend, 0)) AS last7,
    SUM(IF(DATE_DIFF(a.date_dim, a.a_start, DAY) <= CAST(CEIL(0.75 * DATE_DIFF(a.a_end, a.a_start, DAY)) AS INT64) - 1, a.spend, 0)) AS so_far,
    ANY_VALUE(CAST(CEIL(0.75 * DATE_DIFF(a.a_end, a.a_start, DAY)) AS INT64)) AS q_days,
    SUM(IF(DATE_DIFF(a.date_dim, a.a_start, DAY) BETWEEN 0 AND 20, a.spend, 0)) AS s_a,
    SUM(IF(DATE_DIFF(a.date_dim, a.a_start, DAY) BETWEEN 21 AND 27, a.spend, 0)) AS s_b,
    ARRAY_AGG(IF(a.date_dim < a.a_end, a.uniq, NULL) IGNORE NULLS ORDER BY a.date_dim DESC LIMIT 1)[SAFE_OFFSET(0)] AS uniq_end,
    MAX(IF(a.date_dim < a.a_end, a.date_dim, NULL)) = DATE_SUB(ANY_VALUE(a.a_end), INTERVAL 1 DAY)
      AND ARRAY_AGG(IF(a.date_dim < a.a_end, a.lr, NULL) IGNORE NULLS ORDER BY a.date_dim DESC LIMIT 1)[SAFE_OFFSET(0)] >= 0.5
      AND ARRAY_AGG(IF(a.date_dim < a.a_end, a.uac, NULL) IGNORE NULLS ORDER BY a.date_dim DESC LIMIT 1)[SAFE_OFFSET(0)] > 1
      AND NOT LOGICAL_OR(a.excl) AND SUM(a.spend) > 0 AND MAX(b.user_id) IS NULL AS ok
  FROM ud a LEFT JOIN bad b ON b.user_id = a.user_id GROUP BY 1,2),
cl AS (SELECT album_id, ANY_VALUE(album_close_date) AS a_end FROM `solitaire-dreams-411507.bi_prod.user_daily_album` WHERE date_dim BETWEEN DATE '2026-05-15' AND DATE '2026-10-05' AND album_id IN (12, 14, 15) GROUP BY 1),
nx AS (
  SELECT c.album_id, n.user_id, SUM(IFNULL(n.album_spent_today,0)) AS rev7, COUNTIF(IFNULL(n.album_spent_today,0) > 0) AS pay_days7
  FROM `solitaire-dreams-411507.bi_prod.user_daily_album` n JOIN cl c ON n.album_id = c.album_id + 1
  WHERE n.date_dim BETWEEN DATE '2026-06-23' AND DATE '2026-10-12' AND n.date_dim BETWEEN DATE_ADD(c.a_end, INTERVAL 1 DAY) AND DATE_ADD(c.a_end, INTERVAL 7 DAY)
  GROUP BY 1, 2),
t AS (
  SELECT u.album_id, u.user_id, u.alb_rev, u.last7, u.s_a / 21 AS pace_a, u.s_b AS mid7, IFNULL(x.rev7, 0) AS rev7, IFNULL(x.pay_days7, 0) AS pay_days7,
    CASE WHEN u.s_a <= 0 THEN 't0_0' WHEN u.s_a / 21 <= 2 THEN 't1_le2' WHEN u.s_a / 21 <= 5 THEN 't2_2_5'
         WHEN u.s_a / 21 <= 20 THEN 't3_5_20' ELSE 't4_gt20' END AS tier,
    CASE WHEN u.uniq_end >= 144 THEN 'a_finished' WHEN u.uniq_end >= 142 THEN 'b_1_2' WHEN u.uniq_end = 141 THEN 'c_3' ELSE 'd_4plus' END AS status
  FROM u LEFT JOIN nx x USING (album_id, user_id) WHERE u.ok),
tot AS (SELECT album_id, COUNT(*) AS n_all, SUM(alb_rev) AS rev_all FROM t GROUP BY 1)
SELECT t.album_id AS a, tier AS l, status AS s, COUNT(*) AS n, ROUND(SUM(alb_rev) / ANY_VALUE(rev_all), 4) AS sr,
  ROUND(SUM(pace_a)) AS pace_a, ROUND(SUM(mid7)) AS mid7, ROUND(SUM(rev7)) AS after7
FROM t JOIN tot USING (album_id) WHERE tier != 't0_0' GROUP BY 1, 2, 3 ORDER BY 1, 2, 3;

