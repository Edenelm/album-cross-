# Builds claude/topic6_payout_prizes_3albums_2026-10-24.sql: the latest-album payout-with-prizes query
# (topic6_payout_prizes_by_level_2026-10-24.sql) re-run for the two earlier albums of the agreed 3-album set.
# Every DATE literal in a game's section is shifted by (new close - latest close); album id is swapped.
import re, datetime as dt
src = open('topic6_payout_prizes_by_level_2026-10-24.sql').read()
parts = re.split(r'(?m)^-- ===== ', src)
sec = {p.split()[0]: '-- ===== ' + p for p in parts[1:]}
D = lambda s: dt.date.fromisoformat(s)
jobs = [('DISNEY', 15, '2026-10-05', [(12, '2026-06-22'), (14, '2026-08-24')]),
        ('DOMINO', 20, '2026-10-12', [(17, '2026-05-11'), (19, '2026-08-24')]),
        ('DICE',   63, '2026-09-07', [(59, '2026-06-22'), (61, '2026-07-27')])]
out = ['-- Topic 6 (Eden 2026-10-24): payout with album prizes for the 3-album set (earlier two albums per game).',
       '-- Generated by topic6_payout_3albums_gen_2026-10-24.py from topic6_payout_prizes_by_level_2026-10-24.sql (dates shifted by close date).',
       '-- Results: claude/topic6-payout-3albums-2026-10-24.md', '']
for g, old_id, old_close, news in jobs:
    s = sec[g]
    for new_id, new_close in news:
        delta = D(new_close) - D(old_close)
        t = re.sub(r"DATE '(\d{4}-\d{2}-\d{2})'",
                   lambda m: m.group(0) if m.group(1) == '2023-11-01' else "DATE '%s'" % (D(m.group(1)) + delta), s)
        t = t.replace('album_id = %d' % old_id, 'album_id = %d' % new_id)
        t = re.sub(r'(?m)^-- ===== .*', '-- ===== %s %d (close %s) =====' % (g, new_id, new_close), t, count=1)
        out.append(t.strip() + '\n')
open('topic6_payout_prizes_3albums_2026-10-24.sql', 'w').write('\n'.join(out))
